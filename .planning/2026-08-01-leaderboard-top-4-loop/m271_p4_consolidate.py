def build() -> tuple[xg.ExcavationGraph, DeficitLedger]:
    ledger = DeficitLedger.from_a7()
    ledger.compute_efficiency()

    graph = xg.ExcavationGraph()
    for code, description, holds in PREMISES:
        graph.register_premise(xg.Premise(code, description, holds))

    graph.add_node("N0", node_type="MEASURE", lane="L8", status=xg.LIVE,
                   summary="데이터 정밀 분석 및 특성 정밀 파악")
    for node_id, lane, summary in N0_NODES:
        graph.add_node(node_id, node_type="MEASURE", lane=lane, parents=["N0"],
                       status=xg.LIVE, summary=summary)

    # 노드를 **전부 먼저** 만들고 폐기는 마지막에 적용한다. 폐기가 흡수 상태이므로
    # 순서를 뒤집으면 후속 노드를 만들 수 없다.
    # `CYCLES` 의 parent 는 **시간순**이지 의존이 아니다. 사이클 n+1 이 n 의 결론 위에
    # 서는 경우는 오히려 드물고, 대개는 n 이 드러낸 결함을 고치거나 다른 질문으로
    # 옮겨간다. 이 사슬을 `depends_on` 으로 걸면 폐기가 무차별로 번진다 — 실제로
    # `C1N32` 의 폐기가 30 개 노드를 삼켰고 그 안에 현재 챔피언을 만든 `C1N35` 가
    # 있었다. 기본을 `follows` 로 두고, **방어할 수 있는 의존만** 아래에서 명시한다.
    # 두 패스로 나눈다 — 노드를 전부 만든 뒤에 간선을 건다. 한 루프에서 하면
    # `CYCLES` 의 나열 순서가 곧 제약이 되어, 뒤에 선언된 노드를 부모로 쓸 수 없다.
    for node_id, lane, _parent, summary, _ in CYCLES:
        graph.add_node(node_id, node_type="EXPERIMENT", lane=lane,
                       status=xg.LIVE, summary=summary)
    for node_id, _lane, parent, _summary, _ in CYCLES:
        graph.link(parent, node_id, "follows")
    for child, parent in DEPENDS_ON:
        graph.link(parent, child, "depends_on")
    for source, target in SUPERSESSIONS:
        graph.link(source, target, "supersedes")

    # 결손 셀을 DEFICIT 노드로. 회수가능질량 상위만 그래프에 올린다.
    for cell in ledger.top(20):
        graph.add_node(cell["key"], node_type="DEFICIT", lane="L8", status=xg.LIVE,
                       recoverable=cell["recoverable_if_average"],
                       excess=cell["excess_ratio"])

    for node_id, _, _, _, premise in CYCLES:
        if premise:
            graph.prune(node_id, premise)

    # 미사용 컬럼 축은 A2 증거로 닫는다 (C14 CLOSE_AXIS).
    graph.add_node("AXIS_UNUSED_COLUMNS", node_type="EXPERIMENT", lane="L2",
                   parents=["A2_columns"], status=xg.LIVE,
                   summary="미사용 NWP 컬럼 확장")
    graph.prune("AXIS_UNUSED_COLUMNS", "UNUSED_COLUMNS_CARRY_LITTLE")

    # 가용성 회수 축도 닫는다 (기전은 확인됐으나 예보 시점 미지).
    graph.add_node("AXIS_AVAILABILITY_RECOVERY", node_type="EXPERIMENT", lane="L3",
                   parents=["C1N2_COLLIDER_CORRECTED"], status=xg.LIVE,
                   summary="터빈 가용성 회수")
    graph.prune("AXIS_AVAILABILITY_RECOVERY", "AVAILABILITY_UNKNOWABLE_AT_FORECAST")

    return graph, ledger


